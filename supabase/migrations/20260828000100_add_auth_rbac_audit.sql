-- Current planning tables are readable by active users and writable by admins.
do $$
declare
  table_name text;
begin
  foreach table_name in array array['planning_runs', 'ol_demand', 'sfdc_pipeline', 'bulk_deals', 'historical_actuals', 'demand_confirmations']
  loop
    if to_regclass(format('public.%I', table_name)) is null then
      continue;
    end if;
    execute format('alter table public.%I enable row level security', table_name);
    execute format('create policy %I on public.%I for select to authenticated using (exists (select 1 from core.app_user u where u.user_id = auth.uid() and u.active))', table_name || '_user_select', table_name);
    execute format('create policy %I on public.%I for insert to authenticated with check (core.is_admin())', table_name || '_admin_insert', table_name);
    execute format('create policy %I on public.%I for update to authenticated using (core.is_admin()) with check (core.is_admin())', table_name || '_admin_update', table_name);
    execute format('create policy %I on public.%I for delete to authenticated using (core.is_admin())', table_name || '_admin_delete', table_name);
  end loop;
end;
$$;

alter default privileges in schema core revoke all on tables from anon;
alter default privileges in schema core grant select on tables to authenticated;
