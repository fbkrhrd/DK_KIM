-- STEP 2: Auth profile, RBAC, and audit trail.
-- Existing SCM calculation views and formulas are intentionally unchanged.

create schema if not exists core;

create table if not exists core.app_user (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  name text,
  department text,
  role text not null default 'USER' check (role in ('ADMIN', 'USER')),
  active boolean not null default true,
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists core.audit_log (
  id bigint generated by default as identity primary key,
  actor uuid references auth.users(id) on delete set null,
  action text not null,
  target_type text not null,
  target_id text not null,
  before jsonb,
  after jsonb,
  at timestamptz not null default now()
);

create index if not exists app_user_role_active_idx on core.app_user(role, active);
create index if not exists audit_log_target_idx on core.audit_log(target_type, target_id);
create index if not exists audit_log_at_idx on core.audit_log(at desc);

create or replace function core.set_updated_at()
returns trigger
language plpgsql
set search_path = core, pg_temp
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists app_user_set_updated_at on core.app_user;
create trigger app_user_set_updated_at
  before update on core.app_user
  for each row execute function core.set_updated_at();

create or replace function core.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = core, public, pg_temp
as $$
begin
  insert into core.app_user (user_id, email, name, department)
  values (
    new.id,
    coalesce(new.email, ''),
    new.raw_user_meta_data ->> 'name',
    new.raw_user_meta_data ->> 'department'
  )
  on conflict (user_id) do update
    set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function core.handle_new_auth_user();

insert into core.app_user (user_id, email, name, department)
select id, coalesce(email, ''), raw_user_meta_data ->> 'name', raw_user_meta_data ->> 'department'
from auth.users
on conflict (user_id) do update set email = excluded.email;

create or replace function core.is_admin()
returns boolean
language sql
stable
security definer
set search_path = core, pg_temp
as $$
  select exists (
    select 1
    from core.app_user
    where user_id = auth.uid()
      and role = 'ADMIN'
      and active = true
  );
$$;

revoke all on function core.is_admin() from public;
grant execute on function core.is_admin() to authenticated;

create or replace function core.touch_last_login()
returns void
language sql
security definer
set search_path = core, pg_temp
as $$
  update core.app_user
     set last_login_at = now(), updated_at = now()
   where user_id = auth.uid()
     and active = true;
$$;

revoke all on function core.touch_last_login() from public;
grant execute on function core.touch_last_login() to authenticated;

create or replace function core.audit_app_user_change()
returns trigger
language plpgsql
security definer
set search_path = core, public, pg_temp
as $$
begin
  if old.role is distinct from new.role then
    insert into core.audit_log(actor, action, target_type, target_id, before, after)
    values (
      auth.uid(), 'USER_ROLE_CHANGED', 'app_user', new.user_id::text,
      jsonb_build_object('role', old.role),
      jsonb_build_object('role', new.role)
    );
  end if;

  if old.active is distinct from new.active then
    insert into core.audit_log(actor, action, target_type, target_id, before, after)
    values (
      auth.uid(), case when new.active then 'USER_ACTIVATED' else 'USER_DEACTIVATED' end,
      'app_user', new.user_id::text,
      jsonb_build_object('active', old.active),
      jsonb_build_object('active', new.active)
    );
  end if;
  return new;
end;
$$;

drop trigger if exists app_user_audit_change on core.app_user;
create trigger app_user_audit_change
  after update on core.app_user
  for each row execute function core.audit_app_user_change();

-- Remove broad policies from the existing exposed data tables.
do $$
declare
  p record;
begin
  for p in
    select schemaname, tablename, policyname
    from pg_policies
    where (schemaname = 'core' and tablename in ('app_user', 'audit_log', 'leadtime_plan', 'usage_profile', 'supplier_alias'))
       or (schemaname = 'public' and tablename in ('planning_runs', 'ol_demand', 'sfdc_pipeline', 'bulk_deals', 'historical_actuals', 'demand_confirmations'))
  loop
    execute format('drop policy if exists %I on %I.%I', p.policyname, p.schemaname, p.tablename);
  end loop;
end;
$$;

