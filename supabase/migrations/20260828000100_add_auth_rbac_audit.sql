alter table core.app_user enable row level security;
alter table core.audit_log enable row level security;

create policy app_user_select on core.app_user
  for select to authenticated
  using (active = true and user_id = auth.uid() or core.is_admin());

create policy app_user_admin_update on core.app_user
  for update to authenticated
  using (core.is_admin() and user_id <> auth.uid())
  with check (core.is_admin() and user_id <> auth.uid());

create policy audit_log_admin_select on core.audit_log
  for select to authenticated
  using (core.is_admin());

